import { CATALOGUE } from "./catalogue.ts";

export const START = "<!-- catalogue:start (generated by `npm run docs`, do not edit) -->";
export const END = "<!-- catalogue:end -->";

/** The channel catalogue as a Markdown table. */
export function catalogueMarkdown(): string {
  const rows = CATALOGUE.map((c) => {
    const frozen = c.frozenCheck ? " Checked for frozen values." : "";
    return `| \`${c.id}\` | ${c.unit || "–"} | ${c.kind} | ${c.group} | ${c.description}${frozen} |`;
  });
  return ["| Id | Unit | Kind | Group | Meaning |", "|---|---|---|---|---|", ...rows].join("\n");
}

/** Replaces the generated block between the markers. */
export function replaceGenerated(text: string, block: string): string {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error("README.md has no catalogue markers.");
  return text.slice(0, a + START.length) + "\n" + block + "\n" + text.slice(b);
}
